"""Edge cases for the disk file device's mount prefix replacement
(game/loading/mount_resolve.cpp), for tools/verify.py run.

usage: mount_resolve_cases.py OUT_DIR [root|alias]

Each case lays out a device (`device`) whose root table (+0x58) or alias table (+0x80) points at
synthetic mount entries (`entries`, 0x70 bytes each: name and target wide strings, text inline up
to 7 characters, longer text in its own buffer) and a path wide string (`path`). The other table
holds decoy entries that would match. The C library calls are scripted imports, generated by
walking the path as the code does: wcslen, wcschr against the game's separator set (L":"),
wcsncmp against same-length names, and for a match wcslen and wmemcmp against "title". The string
replace (0x02b25360) is a scripted stub; the token scanner (0x02a2aca0) runs as the original.
"""
import json
import os
import struct
import sys

ADDRESSES = {'root': '0x0246cf50', 'alias': '0x0246d180'}
TABLES = {'root': 0x58, 'alias': 0x80}
REPLACE = '0x02b25360'
SEPARATOR_SET = 0x04dc10aa      # L":" in the executable; its terminator is 2 bytes on
TITLE = 'title'
ENTRY = 0x70
TARGET = 0x38
INLINE_CAPACITY = 8
NPOS = 0xffffffffffffffff


def u64(v):
    return struct.pack('<Q', v & NPOS).hex()


def sign(v):
    return (v > 0) - (v < 0)


def wcsncmp(a, b, n):
    for i in range(n):
        ca = a[i] if i < len(a) else '\0'
        cb = b[i] if i < len(b) else '\0'
        if ca != cb:
            return sign(ord(ca) - ord(cb))
        if ca == '\0':
            return 0
    return 0


def wmemcmp(a, b, n):
    for i in range(n):
        if a[i] != b[i]:
            return sign(ord(a[i]) - ord(b[i]))
    return 0


class Case:
    def __init__(self, which, cid):
        self.which = which
        self.cid = cid
        self.buffers = {}
        self.memory = []
        self.imports = []
        self.stubs = []

    def string(self, buf, offset, text, size=None, heap_null=False, capacity=None):
        """A wide string at buf+offset; returns its text as the code sees it."""
        size = len(text) if size is None else size
        if capacity is None:
            capacity = INLINE_CAPACITY - 1 if len(text) < INLINE_CAPACITY else len(text) + 3
        raw = bytearray(self.buffers[buf]['raw'])
        raw[offset + 0x18:offset + 0x28] = struct.pack('<QQ', size, capacity)
        if capacity < INLINE_CAPACITY:
            encoded = (text + '\0').encode('utf-16-le')
            raw[offset + 8:offset + 8 + len(encoded)] = encoded
        elif not heap_null:
            name = f'text_{buf}_{offset:x}'
            encoded = (text + '\0' * 8).encode('utf-16-le')
            self.buffers[name] = {'raw': encoded}
            self.memory.append({'addr': f'buf:{buf}+{offset + 8}', 'pointer': f'{name}+0'})
        raw[offset + 0x28:offset + 0x30] = struct.pack('<Q', 0x5a5a0000 + offset)   # allocator
        self.buffers[buf]['raw'] = bytes(raw)
        return None if heap_null and capacity >= INLINE_CAPACITY else text

    def table(self, table_offset, names, buf):
        self.buffers[buf] = {'raw': bytes(ENTRY * max(len(names), 1))}
        for i, name in enumerate(names):
            self.string(buf, ENTRY * i, name)
            self.string(buf, ENTRY * i + TARGET, f'/app{i}/')
        self.memory.append({'addr': f'buf:device+{table_offset + 8}', 'pointer': f'{buf}+0'})
        self.memory.append({'addr': f'buf:device+{table_offset + 16}', 'pointer': f'{buf}+{ENTRY * len(names)}'})

    def wcschr(self, ch):
        if ch == ':':
            ret = f'guest:0x{SEPARATOR_SET:08x}'
        elif ch == '\0':
            ret = f'guest:0x{SEPARATOR_SET + 2:08x}'
        else:
            ret = 0
        self.imports.append({'name': 'wcschr', 'argc': 2, 'ret': ret})
        return ret != 0

    def script(self, names, text, path_size):
        """The calls the code makes, generated as it walks the path."""
        if not names or text is None:
            return
        text = text + '\0' * 8
        remaining = text.index('\0')
        self.imports.append({'name': 'wcslen', 'argc': 1, 'ret': remaining})
        at = 0
        while remaining and self.wcschr(text[at]):
            at += 1
            remaining -= 1
        if text[at] == '\0' or not remaining:
            return
        start, length = at, 0
        while remaining:
            if self.wcschr(text[at]):
                break
            at += 1
            length += 1
            remaining -= 1
        token = text[start:start + length]
        if not remaining:
            return
        while self.wcschr(text[at]):
            at += 1
            if remaining == 1:
                return
            remaining -= 1
        if text[at] == '\0' or path_size < length + 2:
            return
        for i, name in enumerate(names):
            if len(name) != length:
                continue
            order = wcsncmp(token, name, length)
            self.imports.append({'name': 'wcsncmp', 'argc': 3, 'ret': order & 0xffffffff})
            if order:
                continue
            self.stubs.append({'address': REPLACE, 'argc': 6, 'ret': 'buf:path'})
            self.imports.append({'name': 'wcslen', 'argc': 1, 'ret': len(TITLE)})
            common = min(len(name), len(TITLE))
            if common:
                self.imports.append({'name': 'wmemcmp', 'argc': 3,
                                     'ret': wmemcmp(name, TITLE, common) & 0xffffffff})
            return

    def json(self):
        return {'schema': 1, 'address': ADDRESSES[self.which], 'id': self.cid, 'returns': 'i8',
                'args': {'rdi': 'buf:device', 'rsi': 'buf:path'},
                'buffers': {k: {'size': len(v['raw']), 'bytes': v['raw'].hex()} for k, v in self.buffers.items()},
                'memory': self.memory, 'imports': self.imports, 'stubs': self.stubs}


def case(which, cid, names, path, path_size=None, heap_null=False, path_capacity=None):
    c = Case(which, cid)
    c.buffers['device'] = {'raw': bytes(0xa8)}
    c.buffers['path'] = {'raw': bytes(0x38)}
    other = 'alias' if which == 'root' else 'root'
    c.table(TABLES[other], ['title', 'data', 'x'], 'decoys')
    if names is not None:
        c.table(TABLES[which], names, 'entries')
    size = len(path) if path_size is None else path_size
    text = c.string('path', 0, path, size=size, heap_null=heap_null, capacity=path_capacity)
    c.script(names, text, size)
    return c.json()


def cases(which):
    common = ['data', 'title', 'sound', 'dlc1']
    return [
        case(which, 'no_table', None, 'data:/x.bin'),
        case(which, 'empty_table', [], 'data:/x.bin'),
        case(which, 'first_entry', common, 'data:/param/x.bin'),
        case(which, 'title_root', common, 'title:/shader/x.bin'),
        case(which, 'later_entry_heap_path', common, 'sound:/frpg_main.fsb'),
        case(which, 'unknown_mount', common, 'other:/x.bin'),
        case(which, 'same_length_differs', ['dat0', 'data'], 'data:/x'),
        case(which, 'first_of_duplicates', ['data', 'data'], 'data:/x'),
        case(which, 'longer_title_name', ['titles'], 'titles:/x'),
        case(which, 'shorter_title_name', ['titl'], 'titl:/x'),
        case(which, 'long_mount_name', ['savedatafiles', 'data'], 'savedatafiles:/x'),
        case(which, 'no_separator', common, 'data'),
        case(which, 'separator_last', common, 'data:'),
        case(which, 'separators_only_after', common, 'data:::'),
        case(which, 'double_separator', common, 'data::x'),
        case(which, 'leading_separator', common, ':data:/x'),
        case(which, 'empty_path', common, ''),
        case(which, 'only_separators', common, '::::'),
        case(which, 'size_too_small', common, 'data:/x', path_size=5),
        case(which, 'size_just_enough', common, 'data:/', path_size=6),
        case(which, 'heap_text_null', common, 'data:/long/path', heap_null=True),
        case(which, 'empty_name_entry', ['', 'data'], 'data:/x'),
        case(which, 'case_differs', common, 'DATA:/x'),
    ]


def main():
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] not in ADDRESSES):
        sys.exit(__doc__)
    out = sys.argv[1]
    which = sys.argv[2] if len(sys.argv) == 3 else 'root'
    os.makedirs(out, exist_ok=True)
    generated = cases(which)
    for c in generated:
        with open(os.path.join(out, f"{c['id']}.json"), 'w') as f:
            json.dump(c, f, indent=1)
    print(f'{len(generated)} cases in {out}')


if __name__ == '__main__':
    main()
