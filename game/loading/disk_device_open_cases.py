"""Edge cases for opening a path through the disk file device
(game/loading/disk_device_open.cpp), for tools/verify.py run.

usage: disk_device_open_cases.py OUT_DIR open|find|device|unnamed

All modes lay out a device buffer (`device`, 0x100 bytes of a pattern) whose lock at +0xe0 has a
fake vtable with scripted lock and unlock slots, and a path wide string (`path`, synthetic text,
inline up to 7 characters, longer text in its own buffer). Each string allocator is a fake object
whose vtable has scripted slots: 0x10 (the query an assignment makes), 0x20 (the heap info, which
writes the flags byte) and 0x70 (free).

find (0x0246e630): synthetic named devices (+0xb0, 0x48-byte entries: name string, device). The C
library calls are scripted imports generated by walking the path as the code does: wcslen,
wcschr against the game's separator set (L":") for the token scanner (0x02a2aca0, run as the
original) and the separators after it, then wcslen of each entry's name and wcsncmp for names of
the token's length.

device (0x0246e810) and unnamed (0x0246e9a0): fake file devices whose vtable's open slot is a
scripted stub returning a file or null; for unnamed, a device list (+0x08) and named devices.
The path copy heap (0x05940668) is set, or null and found through a scripted 0x0247bbf0. The
string assign (0x02a279a0) is a scripted stub that may give the working copy a heap buffer (so it
is freed).

open (0x0246d550): the thread's temporary heap at a thread-local slot; wcslen and the string
assign from text (0x02a2a310) scripted; the alias and root resolutions (0x0246d180, 0x0246cf50)
scripted as sequences of results; the named device lookup and both opens scripted stubs.
"""
import json
import os
import struct
import sys

ADDRESSES = {'open': '0x0246d550', 'find': '0x0246e630', 'device': '0x0246e810', 'unnamed': '0x0246e9a0'}
RETURNS = 'i64'
# What is compared of a string on the stack: the first character and the fields from the size on
# (the first word and the rest of the inline text are left as the stack had them).


def stack_string(arg, owns=True):
    return [{'arg': arg, 'offset': 8, 'size': 2}, {'arg': arg, 'offset': 0x18, 'size': 0x19 if owns else 0x18}]

LOCK, UNLOCK, QUERY, INFO, FREE, OPEN = '0x00500200', '0x00500240', '0x00500280', '0x005002c0', '0x00500300', '0x00500340'
FATAL_ERROR, ASSIGN_PART, ASSIGN_TEXT = '0x024b55b0', '0x02a279a0', '0x02a2a310'
RESOLVE_ROOT, RESOLVE_ALIAS = '0x0246cf50', '0x0246d180'
FIND, OPEN_ON_DEVICE, OPEN_ON_UNNAMED = '0x0246e630', '0x0246e810', '0x0246e9a0'
COPY_HEAP, COPY_HEAP_OWNER, COPY_HEAP_OFFSET = '0x05940668', '0x0247bbf0', 0x458
THREAD_HEAP_OFFSET, TLS_SLOT = '0x057e4568', -0x100
SEPARATOR_SET = 0x04dc10aa
DEVICE, ENTRY, LOCK_OFFSET, DISABLED = 0x100, 0x48, 0xe0, 0xf8
VALID = 0x20


def u64(v):
    return struct.pack('<Q', v & 0xffffffffffffffff).hex()


def sign(v):
    return (v > 0) - (v < 0)


def wcsncmp(a, b, n):
    for i in range(n):
        ca = a[i] if i < len(a) else '\0'
        cb = b[i] if i < len(b) else '\0'
        if ca != cb:
            return sign(ord(ca) - ord(cb))
        if ca == '\0':
            return 0
    return 0


class Case:
    def __init__(self, mode, cid, fill=0x6b):
        self.mode = mode
        self.cid = cid
        self.raw = {'device': bytearray([fill]) * DEVICE, 'heap_vtable': bytearray(0x78)}
        self.memory = [{'addr': f'buf:device+{LOCK_OFFSET}', 'pointer': 'lock_vtable+0'},
                       {'addr': 'buf:lock_vtable+24', 'guest': LOCK},
                       {'addr': 'buf:lock_vtable+40', 'guest': UNLOCK},
                       {'addr': 'buf:heap_vtable+16', 'guest': QUERY},
                       {'addr': 'buf:heap_vtable+32', 'guest': INFO},
                       {'addr': 'buf:heap_vtable+112', 'guest': FREE}]
        self.raw['lock_vtable'] = bytearray(0x30)
        self.imports = []
        self.stubs = []
        self.args = {'rdi': 'buf:device', 'rsi': 'buf:path'}
        self.extra = {}
        self.heaps = 0

    def heap(self, name=None):
        """A fake allocator object (its vtable is the shared scripted one)."""
        name = name or f'heap{self.heaps}'
        self.heaps += 1
        self.raw[name] = bytearray(0x30)
        self.memory.append({'addr': f'buf:{name}+0', 'pointer': 'heap_vtable+0'})
        return name

    def string(self, buf, offset, text, owns=1, heap_null=False):
        """A wide string at buf+offset; returns its text as the code sees it (None for a null heap)."""
        raw = self.raw[buf]
        inline = len(text) < 8
        raw[offset + 0x18:offset + 0x28] = struct.pack('<QQ', len(text), 7 if inline else len(text) + 3)
        if inline:
            encoded = (text + '\0').encode('utf-16-le')
            raw[offset + 8:offset + 8 + len(encoded)] = encoded
        elif heap_null:
            raw[offset + 8:offset + 16] = bytes(8)
        else:
            name = f'text_{buf}_{offset:x}'
            self.raw[name] = bytearray((text + '\0' * 8).encode('utf-16-le'))
            self.memory.append({'addr': f'buf:{buf}+{offset + 8}', 'pointer': f'{name}+0'})
        raw[offset + 0x30] = owns
        allocator = self.heap()
        self.memory.append({'addr': f'buf:{buf}+{offset + 0x28}', 'pointer': f'{allocator}+0'})
        return None if heap_null and not inline else text

    def path(self, text, owns=1, heap_null=False):
        self.raw['path'] = bytearray([0x3c]) * 0x38
        return self.string('path', 0, text, owns, heap_null)

    def named(self, entries):
        """Named devices: (name, device buffer name or None for a decoy pointer)."""
        self.raw['named'] = bytearray(ENTRY * max(len(entries), 1))
        for i, (name, device) in enumerate(entries):
            self.string('named', ENTRY * i, name)
            if device:
                self.memory.append({'addr': f'buf:named+{ENTRY * i + 0x38}', 'pointer': f'{device}+0'})
        self.memory.append({'addr': 'buf:device+176', 'pointer': 'named+0'})
        self.memory.append({'addr': 'buf:device+184', 'pointer': f'named+{ENTRY * len(entries)}'})

    def file_device(self, name):
        if 'open_vtable' not in self.raw:
            self.raw['open_vtable'] = bytearray(0x18)
            self.memory.append({'addr': 'buf:open_vtable+16', 'guest': OPEN})
        self.raw[name] = bytearray(0x10)
        self.memory.append({'addr': f'buf:{name}+0', 'pointer': 'open_vtable+0'})

    def info(self, flags):
        self.stubs.append({'address': INFO, 'argc': 3, 'argi': [1, 2],
                           'writes': [{'arg': 0, 'offset': 0, 'bytes': f'{flags:02x}'}]})
        if not flags & VALID:
            self.stubs.append({'address': FATAL_ERROR, 'argc': 3})

    def lock(self):
        self.stubs.append({'address': LOCK, 'argc': 1, 'argu32': [1]})

    def unlock(self):
        self.stubs.append({'address': UNLOCK, 'argc': 1})

    def wcschr(self, ch):
        if ch == ':':
            ret = f'guest:0x{SEPARATOR_SET:08x}'
        elif ch == '\0':
            ret = f'guest:0x{SEPARATOR_SET + 2:08x}'
        else:
            ret = 0
        self.imports.append({'name': 'wcschr', 'argc': 2, 'ret': ret})
        return ret != 0

    def json(self):
        c = {'schema': 1, 'address': ADDRESSES[self.mode], 'id': self.cid, 'returns': RETURNS,
             'args': self.args,
             'buffers': {k: {'size': len(v), 'bytes': bytes(v).hex()} for k, v in self.raw.items()},
             'memory': self.memory, 'imports': self.imports, 'stubs': self.stubs}
        c.update(self.extra)
        return c


# find (0x0246e630)

def find_script(c, entries, text):
    """The imports the lookup makes, generated as it walks the path."""
    if text is None:
        return
    text = text + '\0' * 8
    remaining = text.index('\0')
    c.imports.append({'name': 'wcslen', 'argc': 1, 'ret': remaining})
    at = 0
    while remaining and c.wcschr(text[at]):
        at += 1
        remaining -= 1
    if text[at] == '\0' or not remaining:
        return
    start, length = at, 0
    while remaining:
        if c.wcschr(text[at]):
            break
        at += 1
        length += 1
        remaining -= 1
    token = text[start:start + length]
    if not remaining:
        return
    while c.wcschr(text[at]):
        at += 1
        if remaining == 1:
            return
        remaining -= 1
    if text[at] == '\0':
        return
    for name, _ in entries:
        c.imports.append({'name': 'wcslen', 'argc': 1, 'ret': len(name)})
        if len(name) != length:
            continue
        order = wcsncmp(token, name, length)
        c.imports.append({'name': 'wcsncmp', 'argc': 3, 'ret': order & 0xffffffff})
        if order == 0:
            return


def find_case(cid, entries, path, heap_null=False):
    c = Case('find', cid)
    named = []
    for i, name in enumerate(entries):
        c.file_device(f'dev{i}')
        named.append((name, f'dev{i}'))
    c.named(named)
    text = c.path(path, heap_null=heap_null)
    c.lock()
    find_script(c, named, text)
    c.unlock()
    return c.json()


