# open (0x0246d550)

def open_case(cid, path='chr:/c0000.chrbnd', aliases=(1, 0), roots=(0,), disabled=False, disabled_late=False, named=True, result='buf:file', flags=VALID, long_requested=False):
    """aliases/roots: the scripted resolution results in call order (0 once they run out)."""
    c = Case('open', cid)
    c.raw['file'] = bytearray(8)
    c.raw['device'][DISABLED] = 1 if disabled else 0
    c.args = {'rdi': 'buf:device', 'rsi': 'buf:path', 'rdx': '0x1122334455667788', 'rcx': '0x0'}
    if disabled_late:
        # The path (short text) lives right after the device, so the copy's assign can reach the
        # disabled byte through its text argument: opens become disabled while the copy is made.
        c.raw['device'] += bytearray(0x38)
        c.string('device', DEVICE, path)
        c.args['rsi'] = f'buf:device+{DEVICE}'
        # A non-empty alias table: resolving aliases here would run the original's library calls,
        # which the case does not script.
        c.raw['alias_decoy'] = bytearray(0x70)
        c.memory += [{'addr': 'buf:device+136', 'pointer': 'alias_decoy+0'},
                     {'addr': 'buf:device+144', 'pointer': 'alias_decoy+112'}]
    else:
        c.path(path)
    if disabled:
        return c.json()
    below = -TLS_SLOT
    c.raw['tls'] = bytearray(below + 8)
    # The thread heap object: its allocator (a vtable pointer) at +0x28.
    c.raw['thread_heap'] = bytearray(0x30)
    c.memory += [{'addr': THREAD_HEAP_OFFSET, 'bytes': struct.pack('<q', TLS_SLOT).hex()},
                 {'addr': f'buf:tls+{below}', 'pointer': f'tls+{below}'},
                 {'addr': 'buf:tls+0', 'pointer': 'thread_heap+0'}]
    c.memory.append({'addr': 'buf:thread_heap+40', 'pointer': 'heap_vtable+0'})
    c.extra['gs'] = f'buf:tls+{below}'
    c.info(flags)
    if path:
        c.imports.append({'name': 'wcslen', 'argc': 1, 'ret': len(path)})
    stub = {'address': ASSIGN_TEXT, 'argc': 3, 'argmem': stack_string(0, owns=False)}
    if long_requested:
        c.raw['requested_text'] = bytearray((path + '\0').encode('utf-16-le'))
        stub['writes'] = [{'arg': 0, 'offset': 8, 'pointer': 'requested_text+0'},
                          {'arg': 0, 'offset': 0x18, 'bytes': u64(len(path))},
                          {'arg': 0, 'offset': 0x20, 'bytes': u64(len(path) + 2)}]
    if disabled_late:
        stub['writes'] = [{'arg': 1, 'offset': DISABLED - DEVICE - 8, 'bytes': '01'}]
    c.stubs.append(stub)
    aliases, roots = list(aliases), list(roots)
    if disabled_late:
        for r in roots:
            c.stubs.append({'address': RESOLVE_ROOT, 'argc': 2, 'ret': hex(r)})
        return c.json()
    alias_hit = False
    while True:
        aliased = False
        while True:
            r = aliases.pop(0) if aliases else 0
            c.stubs.append({'address': RESOLVE_ALIAS, 'argc': 2, 'ret': hex(r)})
            if not r:
                break
            aliased = alias_hit = True
        r = roots.pop(0) if roots else 0
        c.stubs.append({'address': RESOLVE_ROOT, 'argc': 2, 'ret': hex(r)})
        if not aliased and r != 1:
            break
    if alias_hit:
        c.lock()
        c.stubs.append({'address': FIND, 'argc': 2, 'ret': 'buf:found' if named else '0x0'})
        if named:
            c.raw['found'] = bytearray(8)
            c.stubs.append({'address': OPEN_ON_DEVICE, 'argc': 5, 'ret': result})
        else:
            c.stubs.append({'address': OPEN_ON_UNNAMED, 'argc': 5, 'ret': result})
        c.unlock()
    if long_requested:
        c.stubs.append({'address': FREE, 'argc': 2})
    return c.json()


