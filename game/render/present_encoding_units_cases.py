"""Synthetic edge cases; helper effects are scripted and are not game recordings.

Usage: present_encoding_units_cases.py OUT_DIR. Generate captures outside the repository.
"""
import json
from pathlib import Path
import sys


def basic(cid, returns="i64", size=512):
    return {
        "schema": 1,
        "address": ADDRESS,
        "id": cid,
        "returns": returns,
        "args": {"rdi": "buf:self"},
        "buffers": {"self": {"size": size, "bytes": "a5" * size}},
        "memory": [],
        "stubs": [],
    }


ADDRESS = "0x02564ed0"


def cases():
    for value in (0, 1, 2, 50, 99, 100, 0xFFFFFFFF, 0xABCDEF0000000001):
        c = basic(f"encoding_{value:x}", size=16)
        c["args"] = {"rdi": hex(value)}
        c["memory"] = []
        yield c


def main():
    """Write deterministic synthetic cases to the requested directory."""
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    generated = list(cases())
    for entry in generated:
        (out / (entry["id"] + ".json")).write_text(json.dumps(entry, indent=2) + "\n")
    print(f"{len(generated)} synthetic edge cases written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
