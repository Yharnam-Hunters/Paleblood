def descriptor_fixture(cid, *, word, metadata, encoding=0, count=1, first=65, second=33, third=1, level=0, flags=0, range_value=0):
    arena = bytearray((0x35 + 29 * index) & 255 for index in range(512))
    descriptor = [
        word,
        encoding,
        first,
        second,
        third,
        count,
        (first << level) & 0xFFFFFFFF if level else 0,
        level,
        0,
        flags,
        metadata,
        range_value,
    ]
    for index, value in enumerate(descriptor):
        struct.pack_into("<I", arena, 128 + index * 4, value)
    return {
        "schema": 1,
        "address": ADDRESS,
        "id": cid,
        "returns": RETURN,
        "args": {"rdi": "buf:arena+32", "rsi": "buf:arena+128", "rdx": 0, "rcx": 0, "r8": 0, "r9": 0},
        "buffers": {"arena": {"size": len(arena), "bytes": arena.hex()}},
        "memory": [],
        "imports": [],
        "stubs": [],
    }


def fixtures():
    """Yield synthetic inputs without calculating expected outputs."""
    registers = ["rdi", "rsi", "rdx", "rcx", "r8", "r9"]
    for index, inputs in enumerate(INPUTS):
        arena = bytearray((0x35 + 29 * i) & 255 for i in range(512))
        for offset, value in inputs.get("words", []):
            struct.pack_into("<I", arena, offset, value & 0xFFFFFFFF)

        def wire(value):
            return (
                "buf:arena+0x" + format(int(value[1:]), "x")
                if isinstance(value, str) and value.startswith("p")
                else hex(value)
            )

        values = [wire(v) for v in inputs["args"]]
        args = {register: (values[i] if i < len(values) else "0x0") for i, register in enumerate(registers)}
        args.update({k: wire(v) for k, v in inputs.get("incoming", {}).items()})
        case = {
            "schema": 1,
            "address": ADDRESS,
            "id": "edge_" + format(index, "04d"),
            "returns": inputs.get("returns", RETURN),
            "args": args,
            "stack": values[6:],
            "buffers": {"arena": {"size": len(arena), "bytes": arena.hex()}},
            "memory": [],
            "imports": [],
            "stubs": ([{"address": "0x02abb4a0", "argc": 1, "ret": "0x0"}] if inputs.get("report_stub") else []),
        }
        yield case

    yield descriptor_fixture("range_prt_3d_thick_reduction", word=24, metadata=1, range_value=1, first=1, second=1)
    yield descriptor_fixture("extra_thick_metadata_128_rejected", word=25, metadata=128, first=1, second=1)
    yield descriptor_fixture(
        "unchanged_first_retains_wrapped_byte_count",
        word=0,
        metadata=1,
        range_value=1,
        level=1,
        flags=2,
        first=0x10000000,
        second=1,
    )
    # Complete independent inputs to the small-metadata arithmetic prefix.
    # Larger counts are rejected by the parameter resolver; range scaling below
    # 64 can start only from metadata 1 or 2. Component sizes do not feed this prefix.
    for word in range(32):
        for metadata in (1, 2, 4, 8, 16, 32):
            for count in (1, 2, 4, 8):
                for range_value in (0, 1):
                    if range_value and metadata >= 4:
                        continue
                    cid = f"small_metadata_word{word}_bits{metadata}_count{count}_range{range_value}"
                    yield descriptor_fixture(
                        cid, word=word, metadata=metadata, count=count, flags=2, range_value=range_value
                    )

    # Small mip dimensions force the thick 2D/3D/PRT classes to 1D thick.
    # flags=2 would reject every thick micro-tile category before this fallback.
    for word in (20, 21, 22, 23, 24, 25, 26):
        for metadata in (2, 4, 8, 16):
            yield descriptor_fixture(
                f"thick_mip_fallback_word{word}_bits{metadata}",
                word=word,
                metadata=metadata,
                first=1,
                second=1,
                level=1,
            )
    # Range reduction and metadata thresholds make the final array mode differ
    # from its input table entry. Exercise every thick-category conversion.
    for word in range(19, 27):
        for metadata in (1, 2, 4, 8):
            yield descriptor_fixture(
                f"thick_range_conversion_word{word}_bits{metadata}",
                word=word,
                metadata=metadata,
                first=4096,
                second=4096,
                range_value=1,
            )
    yield descriptor_fixture(
        "extra_thick_2d_converts_to_thick_2d",
        word=25,
        metadata=32,
        first=4096,
        second=4096,
    )
    yield descriptor_fixture(
        "extra_thick_3d_converts_to_thick_3d",
        word=26,
        metadata=32,
        first=4096,
        second=4096,
    )

    # Derive both metadata and the compression range from a nonzero encoding.
    # The second byte deliberately disagrees with the first byte's range class.
    for word in (13, 19):
        for encoding in (0x00002301, 0x0000230E, 0x00000E23, 0x00000E29):
            in_range = 0x23 <= (encoding & 0xFF) <= 0x29
            yield descriptor_fixture(
                f"encoding_04_{encoding:08x}_word{word}",
                word=word,
                metadata=1,
                encoding=encoding,
                range_value=0 if in_range else 1,
            )

    # The first output aliases descriptor flags and enables the late rounding pass.
    case = descriptor_fixture(
        "late_round_flag_from_overlapping_output",
        word=13,
        metadata=8,
        count=1,
        first=4097,
        second=17,
        third=1,
    )
    case["args"]["rdi"] = "buf:arena+164"
    yield case


def main():
    """Write deterministic synthetic cases to the requested directory."""
    destination = Path(sys.argv[1])
    destination.mkdir(parents=True, exist_ok=True)
    cases = list(fixtures())
    for case in cases:
        (destination / (case["id"] + ".json")).write_text(json.dumps(case, indent=1) + "\n")
    print(str(len(cases)) + " synthetic cases written")


if __name__ == "__main__":
    main()
