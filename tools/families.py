"""Function families: many small originals with the same instruction bytes, replaced together.

The compiler emits thousands of identical tiny functions (an empty virtual method is `ret`, a
getter is `mov rax, [rdi+K]; ret`). A family replaces every one of them with one readable body
(one per parameter value), proved by the same differential test as a hand-written function but
run in batches (docs/FAMILIES.md).

Tables, all generated by tools/family_scan.py and checked by tools/validate_functions.py:

symbols/families.csv               one row per family
  family     snake_case name of what the members do (returns_zero)
  system     the game/ directory that holds the replacement and the case generator
  shape      the members' exact bytes: hex bytes and at most one parameter field, for example
             `b8 {u32} c3`. Fields: {u8} one byte, {d8} a positive signed 8-bit displacement,
             {u32} four bytes little-endian. A member's bytes must match the shape exactly.
  returns    the return class its replacement declares (game/hooks.csv's returns column)
  members    how many members the family has, written before the members are generated
  bytes      their total size in bytes, likewise (a member table that differs is refused)
  notes      one line: what the shape means and what it excludes

symbols/families/<family>.csv      one row per member
  address    PS4 virtual address (ascending)
  size       its size in symbols/ghidra_functions.csv
  extent     the bytes up to the next function: the member plus the compiler's NOP padding,
             which the 14-byte hook jump may overwrite (a member needs extent >= 14)
  value      the shape's parameter for this member (hex), empty when the shape has none
  status     replaced, edge-verified or verified (CONTRIBUTING.md)

symbols/families/<family>.verification.csv   tools/verify.py family --record results, one row
  per member in symbols/verification.csv's format.

A member's name is <system>_<family>_<address without 0x>; its replacement is
bb_<system>_<family>, or bb_<system>_<family>_<value> when the shape has a parameter.
"""
from __future__ import annotations

import csv
import io
import os
import re
from dataclasses import dataclass

FAMILY_HEADER = ['family', 'system', 'shape', 'returns', 'members', 'bytes', 'notes']
MEMBER_HEADER = ['address', 'size', 'extent', 'value', 'status']
FAMILIES_TABLE = os.path.join('symbols', 'families.csv')
MEMBERS_DIR = os.path.join('symbols', 'families')
HOOK_JUMP = 14
FAMILY_NAME = re.compile(r'^[a-z][a-z0-9]*(_[a-z0-9]+)*$')
FIELD = re.compile(r'\{(u8|d8|u32)\}')
FIELD_WIDTH = {'u8': 1, 'd8': 1, 'u32': 4}


class ShapeError(ValueError):
    pass


@dataclass(frozen=True)
class Shape:
    """A family's byte template: fixed bytes and at most one parameter field."""
    text: str
    prefix: bytes
    field: str | None
    suffix: bytes

    @property
    def size(self) -> int:
        return len(self.prefix) + (FIELD_WIDTH[self.field] if self.field else 0) + len(self.suffix)

    def value(self, code: bytes) -> int | None:
        """The parameter of CODE when CODE is exactly this shape; None for no parameter.
        Raises ShapeError when CODE does not match."""
        if len(code) != self.size or not code.startswith(self.prefix) or not code.endswith(self.suffix):
            raise ShapeError(f'{code.hex()} is not {self.text}')
        if self.field is None:
            return None
        raw = code[len(self.prefix):len(self.prefix) + FIELD_WIDTH[self.field]]
        value = int.from_bytes(raw, 'little')
        if self.field == 'd8' and not 0 < value < 0x80:
            raise ShapeError(f'{code.hex()}: displacement {value:#x} is not a positive signed byte')
        return value

    def matches(self, code: bytes) -> bool:
        try:
            self.value(code)
        except ShapeError:
            return False
        return True


def parse_shape(text: str) -> Shape:
    parts = text.split()
    if not parts:
        raise ShapeError('empty shape')
    fields = [i for i, p in enumerate(parts) if FIELD.fullmatch(p)]
    if len(fields) > 1:
        raise ShapeError(f'{text}: at most one parameter field')
    for p in parts:
        if not FIELD.fullmatch(p) and not re.fullmatch(r'[0-9a-f]{2}', p):
            raise ShapeError(f'{text}: {p!r} is neither a lowercase hex byte nor a field')
    if not fields:
        return Shape(text, bytes.fromhex(''.join(parts)), None, b'')
    at = fields[0]
    return Shape(text, bytes.fromhex(''.join(parts[:at])), FIELD.fullmatch(parts[at]).group(1),
                 bytes.fromhex(''.join(parts[at + 1:])))


def value_text(value: int | None) -> str:
    return '' if value is None else f'0x{value:x}'


def member_name(family: dict, address: str) -> str:
    return f"{family['system']}_{family['family']}_{address[2:]}"


def replacement(family: dict, value: str) -> str:
    base = f"bb_{family['system']}_{family['family']}"
    return f'{base}_{value}' if value else base


def members_path(root: str, family: str) -> str:
    return os.path.join(root, MEMBERS_DIR, f'{family}.csv')


def verification_path(root: str, family: str) -> str:
    return os.path.join(root, MEMBERS_DIR, f'{family}.verification.csv')


def read_table(path: str, header: list[str]) -> list[dict]:
    """Rows with their line numbers (_line); [] for a missing file. Raises ValueError for a
    wrong header or a short row."""
    if not os.path.isfile(path):
        return []
    with open(path, newline='') as f:
        rows = list(csv.reader(f))
    if not rows or rows[0] != header:
        raise ValueError(f'{path}: header must be {",".join(header)}')
    out = []
    for n, r in enumerate(rows[1:], 2):
        if len(r) != len(header):
            raise ValueError(f'{path}:{n}: expected {len(header)} columns, got {len(r)}')
        out.append(dict(zip(header, r), _line=n))
    return out


def write_table(path: str, header: list[str], rows: list[dict]) -> None:
    out = io.StringIO()
    w = csv.writer(out, lineterminator='\n')
    w.writerow(header)
    for r in rows:
        w.writerow([r[k] for k in header])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + '.tmp'
    with open(tmp, 'w', newline='') as f:
        f.write(out.getvalue())
    os.replace(tmp, path)


def families(root: str) -> list[dict]:
    return read_table(os.path.join(root, FAMILIES_TABLE), FAMILY_HEADER)


def members(root: str, family: str) -> list[dict]:
    return read_table(members_path(root, family), MEMBER_HEADER)


def function_rows(root: str) -> list[dict]:
    """Every family member as a symbols/functions.csv-style row (address, size, name, system,
    status, notes, family), for the tools that count or list functions."""
    out = []
    for fam in families(root):
        for m in members(root, fam['family']):
            out.append({'address': m['address'], 'size': m['size'], 'name': member_name(fam, m['address']),
                        'system': fam['system'], 'status': m['status'], 'notes': fam['notes'],
                        'family': fam['family'], 'extent': m['extent'], 'value': m['value']})
    return out


def source_hash(root: str, family: dict) -> str:
    """The hash verification rows carry: the family's replacement sources and their headers."""
    import verification
    return verification.source_hash(root, f"{family['system']}_{family['family']}", family=True)


def case_module(root: str, system: str):
    """game/<system>/family_cases.py, imported from its path."""
    import importlib.util
    path = os.path.join(root, 'game', system, 'family_cases.py')
    spec = importlib.util.spec_from_file_location(f'family_cases_{system}', path)
    if spec is None or spec.loader is None or not os.path.isfile(path):
        raise FileNotFoundError(f'{path}: no family case generator')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
