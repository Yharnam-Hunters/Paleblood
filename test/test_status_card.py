"""tools/status_card.py: the README status card is derived from symbols/ alone and is stable."""
import datetime
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))

import progress  # noqa: E402
import status_card  # noqa: E402


class StatusCard(unittest.TestCase):
    def test_library_states_agree_with_the_boot_record(self):
        libraries = status_card.library_states(ROOT)
        rt = progress.runtime(ROOT)
        total = sum(sum(c.values()) for c in libraries.values())
        self.assertEqual(total, rt['imports_total'])
        self.assertEqual(sum(c['bundled'] for c in libraries.values()), rt['imports_bundled'])
        self.assertEqual(sum(c['runtime'] for c in libraries.values()), rt['imports_implemented'])
        self.assertEqual(sum(c['stops'] for c in libraries.values()), rt['imports_unresolved'])

    def test_rendering_is_deterministic_and_themed(self):
        cards = status_card.render_all(ROOT)
        self.assertEqual(set(cards), {'docs/assets/status-light.svg', 'docs/assets/status-dark.svg'})
        self.assertEqual(cards, status_card.render_all(ROOT))
        self.assertIn('#fcfcfb', cards['docs/assets/status-light.svg'])
        self.assertIn('#1a1a19', cards['docs/assets/status-dark.svg'])
        for svg in cards.values():
            self.assertTrue(svg.startswith('<svg ') and svg.rstrip().endswith('</svg>'))

    def test_committed_card_is_a_generated_card(self):
        # Whether it is current is checked on main (.github/workflows/progress.yml), which
        # tools/progress_pr.py regenerates; branches leave the card as main has it.
        for name in status_card.render_all(ROOT):
            with open(os.path.join(ROOT, name)) as f:
                svg = f.read()
            self.assertTrue(svg.startswith('<svg ') and 'Generated by tools/status_card.py' in svg, name)

    def test_no_card_without_a_recorded_boot(self):
        import tempfile
        with tempfile.TemporaryDirectory() as empty:
            self.assertEqual(status_card.render_all(empty), {})

    def test_week_counts_back_from_the_newest_boot_not_the_clock(self):
        day = datetime.date(2026, 11, 1)
        history = [{'date': day, 'working': 100}, {'date': day + datetime.timedelta(days=3), 'working': 150},
                   {'date': day + datetime.timedelta(days=9), 'working': 190},
                   {'date': day + datetime.timedelta(days=10), 'working': 230}]
        self.assertEqual(status_card.gained_in_week(history), 80)  # against the day-3 boot
        self.assertEqual(status_card.gained_in_week(history[:2]), 50)  # nothing a week older: the first
        self.assertEqual(status_card.gained_in_week([]), 0)

    def test_a_timeout_is_reported_as_still_running_not_by_address(self):
        rt = {'first_unimplemented': None, 'stopped_by_hook': None, 'runtime_stop': None,
              'fault': {'address': '0x0', 'at': 'host+0x7f801cb7bcc0', 'signal': 0}, 'outcome': 'timeout'}
        stop = progress.boot_stop(rt)
        self.assertIn('still running', stop)
        self.assertNotIn('host+', stop)

    def test_squarify_tiles_the_whole_area_in_proportion(self):
        sizes = [202, 79, 50, 35, 32, 6, 1]
        rects = status_card.squarify(sizes, 10, 20, 600, 400)
        self.assertEqual(len(rects), len(sizes))
        self.assertAlmostEqual(sum(w * h for _, _, w, h in rects), 600 * 400, places=3)
        for size, (x, y, w, h) in zip(sizes, rects):
            self.assertAlmostEqual(w * h, 600 * 400 * size / sum(sizes), places=3)
            self.assertTrue(10 - 1e-6 <= x and x + w <= 610 + 1e-6 and 20 - 1e-6 <= y and y + h <= 420 + 1e-6)

    def test_cells_fit_their_box(self):
        for count, w, h in ((202, 330, 440), (1, 20, 20), (35, 130, 130), (6, 60, 30)):
            columns, size = status_card.cell_grid(count, w, h)
            self.assertLessEqual(columns * size, w + 1e-6)
            self.assertLessEqual(-(-count // columns) * size, h + 1e-6)


if __name__ == '__main__':
    unittest.main()
